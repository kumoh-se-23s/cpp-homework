#include <iostream>
#include <fstream>


#include "Gifted.h"
#include "EmployeeEdu.h"
#include "ShortTermEdu.h"
#include "LifeLong.h"
#include "University.h"
#include "MyString.h"
#include "RAIIUniquePointer.h"

static RAIIUniquePointer<AdStudent> read(std::istream &ifs, bool readKeyManuallyForAutoGenerated) {
    MyString type;
    ifs >> type;
    if (type == "EmployeeEdu") {
        EmployeeEdu g;
        if (readKeyManuallyForAutoGenerated) ifs >> g.key;
        ifs >> g.name >> g.course >> g.position >> g.companyName >> g.phone;
        return {g};
    }
    if (type == "ShortTermEdu") {
        ShortTermEdu g;
        if (readKeyManuallyForAutoGenerated) ifs >> g.key;
        ifs >> g.name >> g.course >> g.department >> g.phone;
        return {g};
    }
    if (type == "Gifted") {
        Gifted g;
        ifs >> g.key >> g.name >> g.middleSchoolName >> g.course >> g.phone >> g.parentName >> g.
                parentPhone;
        return {g};
    }
    if (type == "LifeLong") {
        LifeLong g;
        ifs >> g.key >> g.name >> g.course >> g.courseFee >> g.phone;
        return {g};
    }
    return nullptr;
}


static void write(University &u, MyString &out) {
    std::ofstream ofs(out.getData());
    if (ofs.fail()) {
        std::cout << "failed to open file" << std::endl;
        return;
    }
    ofs << u.toFileFormattedString();
}

int main(int argc, char **argv) {
    if (argc != 2) {
        std::cout << "no input file" << std::endl;
        return 1;
    }
    MyString filename = argv[1];
    std::ifstream ifs(filename.getData());
    if (ifs.fail()) {
        std::cout << "cannot open file" << std::endl;
        return 1;
    }

    University university;
    while (!ifs.eof()) {
        auto v = read(ifs, true);
        if (v) {
            university.insert(std::move(v));
        }
    }


    int mode = 0;
    while (mode != 6) {
        std::cout << "[1] View all / [2] Search / [3] Insert New / [4] Modify / [5] Delete / [6] Exit : ";
        std::cin >> mode;
        switch (mode) {
            case 1: {
                std::cout << university.toString();
                break;
            }
            case 2: {
                std::cout << "Input Course : ";
                MyString input;
                std::cin >> input;
                auto courses = university.searchCourse(input);
                for (int i = 0; i < courses.getSize(); ++i) {
                    std::cout << *courses[i] << "\n";
                }
                break;
            }
            case 3: {
                MyString type;
                std::cout << "Input: ";
                auto v = read(std::cin, false);
                if (v) {
                    if (university.find(v->key)) {
                        std::cout << "<ERROR> The same ID already exists." << std::endl;
                    }
                    else{
                        std::cout << "<INSERT> " << v->toString() << std::endl;
                        university.insert(std::move(v));
                    }
                }
                break;
            }
            case 4: {
                std::cout << "Input ID or Phone Number(XXX-XXXX-XXXX): ";
                MyString input;
                std::cin >> input;
                AdStudent *ptr = university.find(input);
                if (ptr) {
                    std::cout << "Current: " << ptr->toString() << std::endl;
                    university.update(ptr);
                    std::cout << "<UPDATE> " << ptr->toString() << std::endl;
                } else {
                    std::cout << "ID or Phone Number is invalid" << std::endl;
                }
                break;
            }
            case 5: {
                std::cout << "Input ID or Phone Number(XXX-XXXX-XXXX): ";
                MyString input;
                std::cin >> input;
                AdStudent *ptr = university.find(input);
                if (ptr) {
                    MyString ptrStr = ptr->toString();
                    std::cout << ptrStr << " will be deleted. OK? [Y/N]";
                    std::cin >> input;
                    if (input == "Y" || input == "y") {
                        std::cout << "<DELETE> " << ptrStr << std::endl;
                        university.remove(ptr->phone);
                    } else {
                        std::cout << "Canceled." << std::endl;
                    }
                } else {
                    std::cout << "ID or Phone Number is invalid" << std::endl;
                }
                break;
            }
            case 6: {
                MyString input;
                std::cout << "W/w to save changes to " << filename << ", C/c otherwise: ";
                std::cin >> input;
                if (input == "W" || input == "w") {
                    std::cout << " ------ Save Changes and Exit ------ " << std::endl;
                    write(university, filename);
                } else {
                    std::cout << " ------ Exit Without Saving ------ " << std::endl;
                }
                break;
            }
            default: {
                std::cout << "invalid input" << std::endl;
                break;
            }
        }
    }

    return 0;
}
